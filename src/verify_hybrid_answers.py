#!/usr/bin/env python3
"""Evaluate a local Ollama answer verifier against existing MCF/majority baselines.

The gold answer is used only by the evaluator for scoring; it is NEVER included in
any prompt sent to Ollama. Requires only Python's standard library.
"""
import argparse
import csv
import json
import re
import sys
import time
import urllib.error
import urllib.request
from collections import Counter
from decimal import Decimal, InvalidOperation
from pathlib import Path


def clean_answer(value):
    """Extract a comparable numeric answer from GSM8K-style answer text."""
    if value is None:
        return ""
    s = str(value).strip().replace("$", "").replace(",", "")
    # Prefer an explicitly tagged final answer.
    matches = re.findall(r"(?:FINAL_ANSWER|INDEPENDENT_ANSWER|SELECTED_ANSWER|answer)\s*[:=]\s*([-+]?(?:\d+\.?\d*|\.\d+)(?:/\d+)?)", s, re.I)
    if matches:
        return _canonical_number(matches[-1])
    # GSM8K gold answers may contain explanation followed by #### number.
    hashes = re.findall(r"####\s*([-+]?(?:\d+\.?\d*|\.\d+)(?:/\d+)?)", s)
    if hashes:
        return _canonical_number(hashes[-1])
    nums = re.findall(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:/\d+)?", s)
    return _canonical_number(nums[-1]) if nums else ""


def _canonical_number(s):
    try:
        if "/" in s:
            a, b = s.split("/", 1)
            d = Decimal(a) / Decimal(b)
        else:
            d = Decimal(s)
        if not d.is_finite():
            return ""
        return format(d.normalize(), "f")
    except (InvalidOperation, ZeroDivisionError, ValueError):
        return ""


def same_answer(a, b):
    aa, bb = clean_answer(a), clean_answer(b)
    return bool(aa and bb and aa == bb)


def majority_answer(agent_answers):
    parsed = [clean_answer(a) for a in (agent_answers or [])]
    parsed = [a for a in parsed if a]
    if not parsed:
        return ""
    counts = Counter(parsed)
    max_count = max(counts.values())
    winners = sorted(a for a, n in counts.items() if n == max_count)
    # Deterministic tie-break: use the first valid agent answer among tied answers.
    return next((a for a in parsed if a in winners), winners[0])


def call_ollama(base_url, model, question, candidates, timeout, temperature):
    prompt = f'''You are an independent mathematical answer verifier for a GSM8K word problem.
Do not trust the candidate answers merely because they are listed. Solve the problem from the question first, check the arithmetic and units, then compare the candidates.
If a candidate is correct, select its candidate number. If all candidates are wrong, provide your own corrected answer and set selected_candidate to 0.
Do not use any external information. Do not assume a majority is correct.
Return ONLY a JSON object with exactly these keys:
{{"independent_answer":"number only","selected_candidate":0,"selected_answer":"number only","reason":"brief arithmetic check"}}
`selected_candidate` must be 1, 2, or 3 for candidate 1/2/3, or 0 if none is correct. Numeric answers only; no currency symbols or commas.

QUESTION:
{question}

CANDIDATES (answers generated by three separate normal agents):
1: {candidates[0] if len(candidates)>0 else '(missing)'}
2: {candidates[1] if len(candidates)>1 else '(missing)'}
3: {candidates[2] if len(candidates)>2 else '(missing)'}
'''
    payload = {
        "model": model,
        "messages": [
            {"role": "system", "content": "Follow the user's requested JSON output format exactly. Solve math carefully."},
            {"role": "user", "content": prompt},
        ],
        "stream": False,
        "format": "json",
        "options": {"temperature": temperature},
    }
    req = urllib.request.Request(
        base_url.rstrip("/") + "/api/chat",
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        data = json.loads(resp.read().decode("utf-8"))
    content = data.get("message", {}).get("content", "")
    try:
        obj = json.loads(content)
    except json.JSONDecodeError:
        # Salvage a JSON object if the model wrapped it in text.
        match = re.search(r"\{.*\}", content, re.S)
        if not match:
            raise ValueError("Ollama response did not contain valid JSON: " + content[:300])
        obj = json.loads(match.group(0))
    return {
        "independent_answer": clean_answer(obj.get("independent_answer", "")),
        "selected_candidate": int(obj.get("selected_candidate", 0)),
        "selected_answer": clean_answer(obj.get("selected_answer", "")),
        "verifier_reason": str(obj.get("reason", "")),
        "raw_verifier_response": content,
    }


def is_correct(answer, gold):
    return int(same_answer(answer, gold))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--input", default="results/amr_mcf_raw_responses.json", help="Raw MCF JSON input")
    ap.add_argument("--model", default="llama3.2:3b", help="Installed Ollama model name (default: llama3.2:3b)")
    ap.add_argument("--ollama-url", default="http://localhost:11434", help="Ollama base URL")
    ap.add_argument("--output-dir", default="results/analysis", help="Directory for CSV and report")
    ap.add_argument("--limit", type=int, default=0, help="Process only first N questions (0 = all)")
    ap.add_argument("--timeout", type=int, default=180, help="Timeout per question in seconds")
    ap.add_argument("--temperature", type=float, default=0.0, help="Generation temperature (default 0)")
    ap.add_argument("--pause", type=float, default=0.0, help="Seconds to pause between questions")
    ap.add_argument("--resume", action="store_true", help="Resume from existing output CSV, skipping completed question IDs")
    args = ap.parse_args()

    input_path = Path(args.input)
    if not input_path.exists():
        print(f"ERROR: input file not found: {input_path}\nPass --input with the path to amr_mcf_raw_responses(2).json", file=sys.stderr)
        return 2
    try:
        records = json.loads(input_path.read_text(encoding="utf-8"))
    except Exception as exc:
        print(f"ERROR: could not read JSON: {exc}", file=sys.stderr)
        return 2
    if isinstance(records, dict):
        records = records.get("results", records.get("questions", []))
    if not isinstance(records, list) or not records:
        print("ERROR: expected a non-empty JSON list of question records", file=sys.stderr)
        return 2
    if args.limit > 0:
        records = records[:args.limit]

    outdir = Path(args.output_dir)
    outdir.mkdir(parents=True, exist_ok=True)
    csv_path = outdir / "answer_verifier_results.csv"
    report_path = outdir / "answer_verifier_report.txt"
    fields = [
        "question_id", "question", "gold_answer", "mcf_answer", "mcf_correct",
        "majority_answer", "majority_correct", "agent1_answer", "agent2_answer", "agent3_answer",
        "verifier_independent_answer", "verifier_independent_correct", "selected_candidate",
        "verifier_selected_answer", "verifier_selected_correct", "verifier_reason", "error",
    ]
    done = {}
    if args.resume and csv_path.exists():
        with csv_path.open("r", newline="", encoding="utf-8") as f:
            for row in csv.DictReader(f):
                done[str(row.get("question_id", ""))] = row
    mode = "a" if args.resume and csv_path.exists() else "w"
    processed = 0
    with csv_path.open(mode, newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        if mode == "w":
            writer.writeheader()
        for index, rec in enumerate(records, start=1):
            qid = str(rec.get("question_id", index - 1))
            if qid in done:
                print(f"[{index}/{len(records)}] id={qid}: already completed; skipping")
                continue
            question = str(rec.get("question", ""))
            gold = clean_answer(rec.get("gold_answer", ""))
            agents = rec.get("agent_answers") or []
            if not agents and isinstance(rec.get("agent_responses"), list):
                agents = [clean_answer(x) for x in rec["agent_responses"]]
            agents = [clean_answer(x) for x in agents]
            while len(agents) < 3:
                agents.append("")
            mcf = clean_answer(rec.get("mcf_answer", ""))
            majority = majority_answer(agents[:3])
            row = {
                "question_id": qid, "question": question, "gold_answer": gold,
                "mcf_answer": mcf, "mcf_correct": is_correct(mcf, gold),
                "majority_answer": majority, "majority_correct": is_correct(majority, gold),
                "agent1_answer": agents[0], "agent2_answer": agents[1], "agent3_answer": agents[2],
                "verifier_independent_answer": "", "verifier_independent_correct": 0,
                "selected_candidate": "", "verifier_selected_answer": "", "verifier_selected_correct": 0,
                "verifier_reason": "", "error": "",
            }
            try:
                result = call_ollama(args.ollama_url, args.model, question, agents[:3], args.timeout, args.temperature)
                selected_idx = result["selected_candidate"]
                if selected_idx not in (0, 1, 2, 3):
                    selected_idx = 0
                selected_answer = result["selected_answer"]
                # Keep selection self-consistent: if model selects an agent, score that candidate.
                if selected_idx in (1, 2, 3):
                    selected_answer = agents[selected_idx - 1]
                elif not selected_answer:
                    selected_answer = result["independent_answer"]
                row.update({
                    "verifier_independent_answer": result["independent_answer"],
                    "verifier_independent_correct": is_correct(result["independent_answer"], gold),
                    "selected_candidate": selected_idx,
                    "verifier_selected_answer": selected_answer,
                    "verifier_selected_correct": is_correct(selected_answer, gold),
                    "verifier_reason": result["verifier_reason"],
                })
                print(f"[{index}/{len(records)}] id={qid}: MCF={row['mcf_correct']} majority={row['majority_correct']} independent={row['verifier_independent_correct']} selected={row['verifier_selected_correct']}")
            except (urllib.error.URLError, TimeoutError, ValueError, KeyError, TypeError, json.JSONDecodeError) as exc:
                row["error"] = str(exc).replace("\n", " ")[:500]
                print(f"[{index}/{len(records)}] id={qid}: ERROR {row['error']}", file=sys.stderr)
            writer.writerow(row)
            f.flush()
            processed += 1
            if args.pause > 0 and index < len(records):
                time.sleep(args.pause)

    # Re-read the CSV so resumed runs get a complete report, not just this invocation.
    with csv_path.open("r", newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    # Report only rows represented by this input file (and in its ID set).
    wanted = {str(r.get("question_id", i)) for i, r in enumerate(records)}
    rows = [r for r in rows if str(r.get("question_id", "")) in wanted]
    total = len(rows)
    def count_correct(field):
        return sum(str(r.get(field, "0")).strip().lower() in ("1", "true", "yes") for r in rows)
    completed = sum(not r.get("error") for r in rows)
    report = [
        "LOCAL OLLAMA ANSWER-VERIFIER EXPERIMENT",
        f"Input: {input_path}", f"Model: {args.model}", f"Questions in input/evaluation: {total}",
        f"Verifier calls without recorded error: {completed}",
        "",
        "Accuracy (denominator includes all evaluated questions; failures count as incorrect):",
    ]
    for label, field in [
        ("Existing MCF", "mcf_correct"),
        ("Majority voting", "majority_correct"),
        ("Verifier independent solution", "verifier_independent_correct"),
        ("Verifier candidate selection", "verifier_selected_correct"),
    ]:
        n = count_correct(field)
        report.append(f"{label}: {n}/{total} ({100*n/total:.1f}%)" if total else f"{label}: 0/0")
    report += ["", f"Newly processed in this run: {processed}", f"CSV: {csv_path}", f"Report: {report_path}",
               "", "Method note: gold answers were used only for scoring and were not sent to Ollama.",
               "Use these 50 questions as an exploratory comparison, not a held-out benchmark if they were used during development."]
    report_path.write_text("\n".join(report) + "\n", encoding="utf-8")
    print("\n" + "\n".join(report))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
